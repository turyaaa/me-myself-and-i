import {readFile,writeFile,mkdir} from 'node:fs/promises';
const html=(await readFile(new URL('./index.html',import.meta.url),'utf8')).replace(/\r\n/g,'\n');
const raw=html.split('const GROUPS = ')[1].split(';\n// Порядок тем')[0];
const groups=JSON.parse(raw),bank=groups.flatMap(g=>g.cats);
await mkdir(new URL('./dist/',import.meta.url),{recursive:true});
await writeFile(new URL('./dist/index.html',import.meta.url),html);
await writeFile(new URL('./netlify/lib/question-bank.mjs',import.meta.url),'// Generated by build.mjs; never put this module in dist.\nexport default '+JSON.stringify(bank)+';\n');
console.log(`Ready: ${bank.length} categories, standalone HTML and Netlify duel functions.`);
